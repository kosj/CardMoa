-- ============================================================
-- 004: 기존 결제 내역 시간대(KST) 보정 — 한 번만 실행!
-- ============================================================
-- 기존 데이터는 한국 시간(KST) 벽시계 값을 시간대 표시 없이 저장해
-- Postgres가 UTC로 해석 → 실제 시각보다 9시간 앞선 상태로 저장됨.
-- (표시 단계에서 다시 KST로 변환되며 저녁 결제가 다음 날로 밀리는 문제)
--
-- 아래 UPDATE는 저장된 값에서 9시간을 빼 실제 시각으로 바로잡는다.
--
-- ⚠️ 반드시 "한 번만" 실행할 것. 두 번 실행하면 18시간이 빠진다.
-- 코드 수정 이후 새로 저장되는 내역은 +09:00 오프셋으로 정확히 저장되므로
-- 이 스크립트는 기존 데이터에 대해서만 1회 적용한다.
-- ============================================================

UPDATE public.transactions
SET approved_at = approved_at - interval '9 hours';
